(function () {
    // Keywords that identify a monetary input by name or id
    var MONEY_PATTERNS = [
        'price', 'cost', 'rate', 'mrp', 'amount', 'value',
        'discount', 'balance', 'credit', 'advance', 'limit',
        'landing', 'wsp', '_sp', 'selling', 'purchase',
        'basic_cost', 'taxable', 'total', 'subtotal', 'outstanding',
        'opening', 'closing', 'paid', 'due', 'fee', 'charge'
    ];

    // Patterns that should NOT be formatted (qty, count, percent, id fields etc.)
    var EXCLUDE_PATTERNS = [
        'qty', 'quantity', 'count', 'percent', 'pct', '%',
        '_id', 'code', 'pin', 'phone', 'mobile', 'gst', 'hsn',
        'carton', 'stock', 'min_qty', 'max_qty', 'free_qty',
        'slab_order', 'display_order', 'priority', 'year',
        'month', 'day', 'time', 'target_amount_qty'
    ];

    function isMoneyField(el) {
        var key = ((el.name || '') + ' ' + (el.id || '')).toLowerCase();
        if (!key.trim()) return false;
        // Exclude first
        for (var i = 0; i < EXCLUDE_PATTERNS.length; i++) {
            if (key.indexOf(EXCLUDE_PATTERNS[i]) !== -1) return false;
        }
        // Then check if money
        for (var j = 0; j < MONEY_PATTERNS.length; j++) {
            if (key.indexOf(MONEY_PATTERNS[j]) !== -1) return true;
        }
        return false;
    }

    function formatMoney(el) {
        var raw = el.value.trim();
        if (raw === '' || raw === '-') return;
        var num = parseFloat(raw);
        if (isNaN(num)) return;
        el.value = num.toFixed(2);
    }

    // Delegate blur on the whole document (handles dynamically added rows too)
    document.addEventListener('blur', function (e) {
        var el = e.target;
        if (el.tagName !== 'INPUT') return;
        if (el.type !== 'text' && el.type !== 'number' && el.type !== '') return;
        if (el.readOnly || el.disabled) return;
        if (el.dataset.noMoney) return;            // opt-out: data-no-money="1"
        if (isMoneyField(el)) formatMoney(el);
    }, true); // capture phase so it fires before other blur handlers

    // Also format on DOMContentLoaded for pre-filled edit forms
    document.addEventListener('DOMContentLoaded', function () {
        document.querySelectorAll('input[type="text"], input[type="number"], input:not([type])').forEach(function (el) {
            if (el.readOnly || el.disabled || el.dataset.noMoney) return;
            if (!isMoneyField(el)) return;
            var raw = el.value.trim();
            if (raw === '' || raw === '0') return;
            var num = parseFloat(raw);
            if (!isNaN(num) && num !== 0) el.value = num.toFixed(2);
        });
    });
})();
