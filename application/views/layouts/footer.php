// Auto-inject CSRF token into every HTML form on the page
(function() {
    var csrfName  = '<?= $this->security->get_csrf_token_name() ?>';
    var csrfHash  = '<?= $this->security->get_csrf_hash() ?>';
    document.querySelectorAll('form').forEach(function(form) {
        if (!form.querySelector('[name="' + csrfName + '"]')) {
            var inp = document.createElement('input');
            inp.type  = 'hidden';
            inp.name  = csrfName;
            inp.value = csrfHash;
            form.appendChild(inp);
        }
    });
    // Also keep CSRF token in sync for AJAX calls. csrf_regenerate is ON, so the
    // server rotates the hash (and its HttpOnly cookie) on every request —
    // reusing the hash captured at page load 403s any second AJAX call on the
    // same page, and JS can't read the cookie to recover. MY_Controller echoes
    // the fresh hash back as an X-CSRF-TOKEN response header; capture it here
    // and use it for the next send.
    window._csrfName = csrfName;
    $(document).ajaxSend(function(e, xhr, opts) {
        if (opts.type && opts.type.toUpperCase() !== 'GET') {
            var encName = encodeURIComponent(csrfName);
            if (typeof opts.data === 'string') {
                // Strip any stale copy first — a 403-triggered retry re-sends
                // the same settings object, which already has an old value
                // appended by a previous ajaxSend pass.
                var stripped = opts.data.replace(new RegExp('(^|&)' + encName + '=[^&]*'), '');
                opts.data = stripped + (stripped ? '&' : '') + encName + '=' + encodeURIComponent(csrfHash);
            } else if (opts.data instanceof FormData) {
                opts.data.delete(csrfName);
                opts.data.append(csrfName, csrfHash);
            }
        }
    });
    $(document).ajaxComplete(function(e, xhr) {
        var fresh = xhr.getResponseHeader('X-CSRF-TOKEN');
        if (fresh) {
            csrfHash = fresh;
            window._csrfHash = fresh;
            // Also refresh any hidden CSRF field already injected into a form —
            // otherwise a later plain (non-AJAX) form submit on the same page
            // still carries the stale pre-AJAX hash and gets rejected.
            document.querySelectorAll('form [name="' + csrfName + '"]').forEach(function(inp) {
                inp.value = fresh;
            });
        }
    });
    // Background polling elsewhere on the page (offline-sync status, etc.) can
    // race a fresh page load: if the CSRF cookie gets regenerated by another
    // request between this page rendering and the user's first action, the
    // hash embedded above is stale and every POST 403s until a full reload.
    // Recover automatically: on a 403, pull the current hash from a GET-only
    // endpoint (GETs never rotate the token) and retry that one request once.
    $(document).ajaxError(function(e, xhr, settings) {
        if (xhr.status !== 403 || settings.__csrfRetried) return;
        if (!settings.type || settings.type.toUpperCase() === 'GET') return;
        settings.__csrfRetried = true;
        $.get('<?= base_url('csrf/refresh') ?>', function(resp) {
            if (resp && resp.hash) {
                csrfHash = resp.hash;
                window._csrfHash = resp.hash;
            }
            $.ajax(settings);
        }, 'json');
    });
})();
</script>
